"""Aisle & Co. web app API (Spec 05 §5): login, one router per page, KPI catalog, and the built front end."""
from contextlib import asynccontextmanager
from pathlib import Path

import yaml
from fastapi import Depends, FastAPI, HTTPException, Response
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

from app.api import auth, exec_, ops, platform, sales, users
from app.api.db import DW, as_role, connect

ROOT = Path(__file__).resolve().parents[2]
DIST = ROOT / "app/web/dist"


@asynccontextmanager
async def lifespan(_):
    # a rebuilt warehouse (pipeline init --drop) loses the app schema: put it back, with the demo users if none exist
    with connect(DW) as conn:
        conn.execute((Path(__file__).parent / "schema.sql").read_text())
        empty = conn.execute('SELECT NOT EXISTS (SELECT FROM app."user") AS empty').fetchone()["empty"]
    if empty:
        users.seed()
    yield


app = FastAPI(title="Aisle & Co.", docs_url="/api/docs", openapi_url="/api/openapi.json", lifespan=lifespan)
for r in (sales.router, ops.router, exec_.router, platform.router):
    app.include_router(r)


class Login(BaseModel):
    username: str
    password: str


@app.post("/api/login")
def login(body: Login, response: Response):
    user = auth.login(body.username, body.password)
    if not user:
        raise HTTPException(401, "wrong username or password")
    response.set_cookie(auth.COOKIE, auth.cookie_value(user), max_age=auth.MAX_AGE, httponly=True, samesite="lax")
    return me(user)


@app.post("/api/logout")
def logout(response: Response):
    response.delete_cookie(auth.COOKIE)
    return {"ok": True}


@app.get("/api/me")
def me(user: dict = Depends(auth.current_user)):
    with as_role(user["role"]) as q:
        fresh = q.one("SELECT run_id, asof_date, finished_at, now() - finished_at > interval '26 hours' AS stale FROM app.v_data_as_of")
    return {**user, "pages": auth.PAGES[user["role"]], "data_as_of": fresh}


@app.get("/api/catalog/kpis")
def kpis(user: dict = Depends(auth.current_user)):
    return yaml.safe_load((ROOT / "catalog/kpis.yml").read_text())


@app.get("/catalog", include_in_schema=False)
def catalog_page(user: dict = Depends(auth.current_user)):
    """The data catalog (M8), generated by scripts/build_catalog.py; any logged-in role."""
    page = ROOT / "docs/v2/catalog.html"
    if not page.exists():
        raise HTTPException(404, "catalog not built: .venv/bin/python scripts/build_catalog.py")
    return FileResponse(page)


# the single-page front end: static assets, and index.html for every other path
if (DIST / "assets").is_dir():
    app.mount("/assets", StaticFiles(directory=DIST / "assets"), name="assets")


@app.get("/{path:path}", include_in_schema=False)
def spa(path: str):
    if path.startswith("api/"):
        raise HTTPException(404)
    f = DIST / path
    if path and f.is_file() and DIST in f.resolve().parents:
        return FileResponse(f)
    if not (DIST / "index.html").exists():
        return Response("Front end not built: cd app/web && npm install && npm run build", media_type="text/plain")
    return FileResponse(DIST / "index.html")
