"""Executive "Business overview" (Spec 05 §3.4): KPI tiles vs previous month and same month last year, trends, capacity
outlook, lost value, model value, and 3-5 "what changed" sentences generated by rules from the same numbers."""
from fastapi import APIRouter, Depends

from app.api.auth import require
from app.api.db import as_role

router = APIRouter(prefix="/api/exec")
MATURE = 0.9  # a month's cohort conversion is shown once 90 % of its inquiries are decided (open leads would bias it down)


def ym_add(ym: str, n: int) -> str:
    y, m = divmod(int(ym[:4]) * 12 + int(ym[5:]) - 1 + n, 12)
    return f"{y:04d}-{m + 1:02d}"


def status(u):
    """Capacity status thresholds (catalog: capacity_status)."""
    return None if u is None else "Over" if u >= 1 else "Tight" if u >= 0.85 else "OK" if u >= 0.5 else "Quiet"


def month_name(ym: str, year=True) -> str:
    import calendar
    return f"{calendar.month_name[int(ym[5:])]}{' ' + ym[:4] if year else ''}"


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f} %"


def tile(by, key, month, months=12):
    get = lambda m: by.get(m, {}).get(key)
    return {"month": month, "value": get(month), "prev": get(ym_add(month, -1)), "last_year": get(ym_add(month, -12)),
            "spark": [{"month": ym_add(month, i - months + 1), "value": get(ym_add(month, i - months + 1))} for i in range(months)]}


def quarter_util(by, end):
    ms = [ym_add(end, -i) for i in range(3)]
    a = sum(float(by[m]["assigned_hours"] or 0) for m in ms if m in by)
    c = sum(float(by[m]["capacity_hours"] or 0) for m in ms if m in by)
    return round(a / c, 4) if c else None


@router.get("/overview")
def overview(user: dict = Depends(require("exec"))):
    with as_role(user["role"]) as q:
        cur = q.one("SELECT to_char(asof_date, 'YYYY-MM') AS month FROM app.v_data_as_of")["month"]
        kpis = q.all("SELECT * FROM mart_exec.v_monthly_kpis ORDER BY month")
        mix = q.all("SELECT * FROM mart_exec.v_channel_mix WHERE month < %s AND month >= %s", (cur, ym_add(cur, -24)))
        outlook = q.all("SELECT * FROM mart_exec.v_capacity_outlook ORDER BY month, role_group")
        lost = q.all("SELECT * FROM mart_exec.v_lost_value ORDER BY fee_at_stake_estimate DESC NULLS LAST")
        model = q.all("SELECT * FROM mart_exec.v_model_value")
    by = {k["month"]: k for k in kpis}
    report = ym_add(cur, -1)  # the last complete month
    for k in kpis:
        k["decided_share"] = round(k["decided"] / k["inquiries"], 4) if k["inquiries"] and k["decided"] is not None else None
    mature = max((k["month"] for k in kpis if k["month"] <= report and (k["decided_share"] or 0) >= MATURE), default=report)

    tiles = {"bookings": tile(by, "bookings", report), "fee_revenue": tile(by, "fee_revenue", report),
             "conversion_rate": tile(by, "conversion", mature), "median_first_reply": tile(by, "median_first_reply_min", report),
             "turned_away": tile(by, "turned_away", report)}
    tiles["conversion_rate"]["decided"], tiles["conversion_rate"]["inquiries"] = by[mature]["decided"], by[mature]["inquiries"]
    tiles["turned_away"]["fee_at_stake"] = by.get(report, {}).get("fee_at_stake_estimate")
    tiles["ops_utilization_quarter"] = {
        "month": report, "value": quarter_util(by, report), "prev": quarter_util(by, ym_add(report, -3)),
        "last_year": quarter_util(by, ym_add(report, -12)), "from_month": ym_add(report, -2),
        "spark": [{"month": ym_add(report, i - 11), "value": by.get(ym_add(report, i - 11), {}).get("ops_utilization")} for i in range(12)]}

    # channel mix: last 12 complete months vs the 12 before
    def shares(lo, hi):
        rows = [r for r in mix if lo <= r["month"] <= hi]
        tot = sum(r["inquiries"] for r in rows) or 1
        out = {}
        for r in rows:
            o = out.setdefault(r["channel"], {"inquiries": 0, "booked": 0, "decided": 0})
            for f in o:
                o[f] += r[f]
        return {c: {**o, "share": round(o["inquiries"] / tot, 4), "conversion": round(o["booked"] / o["decided"], 4) if o["decided"] else None}
                for c, o in out.items()}
    now_mix, before_mix = shares(ym_add(cur, -12), report), shares(ym_add(cur, -24), ym_add(cur, -13))
    channels = sorted(({"channel": c, "now": now_mix[c], "before": before_mix.get(c)} for c in now_mix), key=lambda r: -r["now"]["share"])

    for o in outlook:
        o["status"] = status(float(o["expected_utilization"]) if o["expected_utilization"] is not None else None)
        o["gap_hours"] = round(max(0.0, float(o["forecast_hours"] or o["booked_hours"] or 0) - float(o["capacity_hours"] or 0)), 0)

    return {"current_month": cur, "report_month": report, "mature_month": mature, "tiles": tiles, "monthly": kpis,
            "channels": channels, "capacity_outlook": outlook, "lost_value": lost, "model_value": model,
            "what_changed": what_changed(by, report, mature, channels, outlook)}


def what_changed(by, report, mature, channels, outlook) -> list[str]:
    s, r, ly = [], by.get(report, {}), by.get(ym_add(report, -12), {})
    if r and ly:
        b, bl = r["bookings"], ly["bookings"]
        trend = "up from" if b > bl else "down from" if b < bl else "the same as"
        s.append(f"{month_name(report, False)} brought {b} bookings worth ฿{float(r['fee_revenue']):,.0f}, {trend} {bl} "
                 f"(฿{float(ly['fee_revenue']):,.0f}) in {month_name(ym_add(report, -12))}.")
    m, mp, my = by.get(mature, {}), by.get(ym_add(mature, -1), {}), by.get(ym_add(mature, -12), {})
    if m.get("conversion") is not None:
        later = "" if mature == report else f" Inquiries received after {month_name(mature)} are still too open to compare."
        s.append(f"Conversion of inquiries received in {month_name(mature)} was {pct(float(m['conversion']))}, "
                 f"against {pct(mp.get('conversion') and float(mp['conversion']))} a month earlier and "
                 f"{pct(my.get('conversion') and float(my['conversion']))} a year earlier.{later}")
    movers = [c for c in channels if c["before"]]
    if movers:
        up = max(movers, key=lambda c: c["now"]["share"] - c["before"]["share"])
        tot_b = sum(c["now"]["booked"] for c in channels)
        tot_d = sum(c["now"]["decided"] for c in channels) or 1
        if up["now"]["share"] - up["before"]["share"] >= 0.03:
            s.append(f"{up['channel']} grew to {pct(up['now']['share'], 0)} of inquiries over the last 12 months (from "
                     f"{pct(up['before']['share'], 0)}) and converts at {pct(up['now']['conversion'])}, against {pct(tot_b / tot_d)} for all channels.")
    over = [o for o in outlook if o["status"] in ("Over", "Tight") and o["month"] > report]
    if over:
        o = max(over, key=lambda o: o["expected_utilization"])
        s.append(f"{o['role_group']} staff are already booked at {pct(float(o['expected_utilization']), 0)} of capacity in "
                 f"{month_name(o['month'])}, before any new bookings.")
    q3 = [ym_add(report, -i) for i in range(3)]
    ta = sum(by.get(x, {}).get("turned_away", 0) for x in q3)
    if ta:
        fee = sum(float(by.get(x, {}).get("fee_at_stake_estimate", 0) or 0) for x in q3)
        s.append(f"{ta} couples were turned away in the last three months because their date was full "
                 f"(fee at stake about ฿{fee:,.0f}, estimate).")
    return s[:5]
