-- =====================================================================
-- Aisle & Co. warehouse, Gold layer (Spec 03): star schema of 5 dimensions and 6 facts.
-- Grain is stated on every table. Ratios are never stored (marts divide). Every dimension has an
-- Unknown member (key -1). DimEmployee is SCD Type 2 (one row per contract version).
-- dbdiagram.io: Import -> PostgreSQL, this file.
-- =====================================================================
CREATE SCHEMA IF NOT EXISTS gold;
CREATE SCHEMA IF NOT EXISTS stg;        -- transient copy of Silver, reloaded each run
CREATE SCHEMA IF NOT EXISTS work;       -- build tables of the transform steps
CREATE SCHEMA IF NOT EXISTS sales_pii;  -- restricted: couples' display names for the Sales list

-- ---------- dimensions ----------
-- grain: one calendar day (2022-2028)
CREATE TABLE gold."DimDate" (
  "DateKey" int PRIMARY KEY,                 -- YYYYMMDD; -1 = unknown / not reached
  "FullDate" date UNIQUE,
  "WeekStart" date, "WeekStartKey" int, "IsoYear" int, "IsoWeek" int,
  "Year" int, "Quarter" int, "Month" int, "MonthName" text, "YearMonth" text, "DayName" text,
  "IsWeekend" boolean, "IsHighSeason" boolean, "IsBuddhistLent" boolean, "LentSource" text,
  "IsPublicHoliday" boolean, "HolidayName" text, "IsValentine" boolean,
  "AuspiciousLevel" text, "AuspiciousTypes" text, "SeasonLabel" text);

-- grain: one marketing channel
CREATE TABLE gold."DimChannel" (
  "ChannelKey" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ChannelID" int UNIQUE, "ChannelName" text, "ChannelType" text, "Platform" text, "TrackingCode" text);

-- grain: one package price version
CREATE TABLE gold."DimPackage" (
  "PackageKey" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PackageID" int UNIQUE, "PackageName" text, "PackageFamily" text, "PackageType" text, "FeeType" text,
  "BasePrice" numeric(12,2), "FeeRate" numeric(5,2), "EffectiveFrom" date, "EffectiveTo" date);

-- grain: one employee contract version (SCD Type 2). A fact on day d joins the version with ValidFrom <= d <= ValidTo.
CREATE TABLE gold."DimEmployee" (
  "EmployeeKey" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ContractID" int UNIQUE, "EmployeeID" int, "EmployeeCode" text, "Nickname" text,
  "RoleName" text, "RoleGroup" text, "EmploymentType" text, "StandardWeeklyHours" numeric(5,2), "MaxConcurrentEvents" int,
  "ValidFrom" date, "ValidTo" date, "IsCurrent" boolean);
CREATE INDEX ON gold."DimEmployee" ("EmployeeID", "ValidFrom", "ValidTo");

-- grain: one combination of outcome labels (junk dimension, ~25 rows)
CREATE TABLE gold."DimInquiryOutcome" (
  "OutcomeKey" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Outcome" text NOT NULL, "FurthestStage" text NOT NULL, "ClosedBy" text NOT NULL, "LostReason" text NOT NULL,
  UNIQUE ("Outcome", "FurthestStage", "ClosedBy", "LostReason"));

INSERT INTO gold."DimDate" ("DateKey", "SeasonLabel", "AuspiciousLevel") VALUES (-1, 'Unknown', 'None');
INSERT INTO gold."DimChannel" VALUES (-1, NULL, 'Unknown', 'Unknown', NULL, NULL);
INSERT INTO gold."DimPackage" ("PackageKey", "PackageName", "PackageFamily", "PackageType") VALUES (-1, 'Unknown', 'Unknown', 'Unknown');
INSERT INTO gold."DimEmployee" ("EmployeeKey", "Nickname", "RoleName", "RoleGroup") VALUES (-1, 'Unknown', 'Unknown', 'Unknown');
INSERT INTO gold."DimInquiryOutcome" VALUES (-1, 'Unknown', 'Unknown', 'N/A', 'N/A');

-- ---------- facts ----------
-- grain: one inquiry (accumulating snapshot: milestone dates fill in as the inquiry moves on)
CREATE TABLE gold."FactInquiry" (
  "InquiryID" int PRIMARY KEY, "CustomerID" int,
  "InquiryDateKey" int NOT NULL REFERENCES gold."DimDate", "FirstReplyDateKey" int NOT NULL REFERENCES gold."DimDate",
  "ConsultationDateKey" int NOT NULL REFERENCES gold."DimDate", "QuoteDateKey" int NOT NULL REFERENCES gold."DimDate",
  "ClosedDateKey" int NOT NULL REFERENCES gold."DimDate", "BookingDateKey" int NOT NULL REFERENCES gold."DimDate",
  "RequestedEventDateKey" int NOT NULL REFERENCES gold."DimDate", "LastActivityDateKey" int NOT NULL REFERENCES gold."DimDate",
  "ChannelKey" int NOT NULL REFERENCES gold."DimChannel", "IndicativePackageKey" int NOT NULL REFERENCES gold."DimPackage",
  "FirstResponderKey" int NOT NULL REFERENCES gold."DimEmployee", "SalesOwnerKey" int NOT NULL REFERENCES gold."DimEmployee",
  "OutcomeKey" int NOT NULL REFERENCES gold."DimInquiryOutcome",
  "BudgetBand" text, "ResponseBand" text, "FirstMessageHour" int,
  "InquiryCount" int NOT NULL, "IsReplied" int, "IsConsulted" int, "IsQuoted" int, "IsBooked" int, "IsOpen" int,
  "IsAutoClosed" int, "IsHoldout" int,
  "ResponseMinutes" numeric(10,1), "DaysToConsult" int, "DaysToQuote" int, "DaysToClose" int, "DaysToBook" int, "LeadDays" int,
  "QuotedAmount" numeric(12,2), "BudgetMidpoint" numeric(12,2),
  "CustomerMessages" int, "StaffMessages" int, "FollowUps" int);

-- grain: one booked wedding
CREATE TABLE gold."FactEventBooking" (
  "EventID" int PRIMARY KEY, "InquiryID" int, "CustomerID" int,
  "BookingDateKey" int NOT NULL REFERENCES gold."DimDate", "EventDateKey" int NOT NULL REFERENCES gold."DimDate",
  "CancelledDateKey" int NOT NULL REFERENCES gold."DimDate",
  "PackageKey" int NOT NULL REFERENCES gold."DimPackage", "ChannelKey" int NOT NULL REFERENCES gold."DimChannel",
  "ComplexityLevel" text, "GuestBand" text,
  "GuestCount" int, "AgreedFee" numeric(12,2), "StaffCount" int,
  "PlannedHoursTotal" numeric(10,2), "PlanningHours" numeric(10,2), "EventDayHours" numeric(10,2),
  "BookingLeadDays" int, "IsCancelled" int NOT NULL);

-- grain: one employee x wedding x week (an assignment's hours placed in the weeks they are worked, Spec 03 §4.3)
CREATE TABLE gold."FactStaffWorkload" (
  "AssignmentID" int NOT NULL, "WeekStartDateKey" int NOT NULL REFERENCES gold."DimDate",
  "EmployeeKey" int NOT NULL REFERENCES gold."DimEmployee", "EventID" int NOT NULL,
  "EventDateKey" int NOT NULL REFERENCES gold."DimDate", "AssignmentRole" text,
  "PlanningHours" numeric NOT NULL, "EventDayHours" numeric NOT NULL, "TotalHours" numeric NOT NULL,   -- unrounded: hours are conserved exactly
  PRIMARY KEY ("AssignmentID", "WeekStartDateKey"));
CREATE INDEX ON gold."FactStaffWorkload" ("WeekStartDateKey", "EmployeeKey");

-- grain: one logged follow-up
CREATE TABLE gold."FactSalesActivity" (
  "ActivityID" int PRIMARY KEY, "ActivityDateKey" int NOT NULL REFERENCES gold."DimDate",
  "SalespersonKey" int NOT NULL REFERENCES gold."DimEmployee", "ChannelKey" int NOT NULL REFERENCES gold."DimChannel",
  "InquiryID" int NOT NULL, "ActivityType" text, "Outcome" text, "FromCallList" int, "ListRank" int, "IsHoldout" int,
  "ActivityCount" int NOT NULL);

-- grain: one open inquiry per score date (written by the conversion model, Spec 04 §7)
CREATE TABLE gold."FactLeadScore" (
  "ScoreDateKey" int NOT NULL REFERENCES gold."DimDate", "InquiryID" int NOT NULL,
  "ChannelKey" int NOT NULL REFERENCES gold."DimChannel", "SalesOwnerKey" int NOT NULL REFERENCES gold."DimEmployee",
  "ModelVersion" text NOT NULL, "Probability" numeric(6,4) NOT NULL, "ExpectedFee" numeric(12,2), "Rank" int, "Band" text,
  "IsHoldout" int NOT NULL, "Reason1" text, "Reason2" text, "Reason3" text, "NextBestAction" text,
  PRIMARY KEY ("ScoreDateKey", "InquiryID"));

-- grain: one forecast date x target week x role group (Spec 04 §11)
CREATE TABLE gold."FactDemandForecast" (
  "ForecastDateKey" int NOT NULL REFERENCES gold."DimDate", "TargetWeekDateKey" int NOT NULL REFERENCES gold."DimDate",
  "RoleGroup" text NOT NULL, "BookedHours" numeric(10,1), "PipelineHours" numeric(10,1), "NewBookingHours" numeric(10,1),
  "P10Hours" numeric(10,1), "P50Hours" numeric(10,1), "P90Hours" numeric(10,1), "CapacityHours" numeric(10,1),
  "ModelVersion" text NOT NULL,
  PRIMARY KEY ("ForecastDateKey", "TargetWeekDateKey", "RoleGroup"));

CREATE TABLE sales_pii.customer_contact (
  customer_id int PRIMARY KEY, display_name text, contact_first_name text, phone_masked text);

CREATE OR REPLACE FUNCTION gold.dk(d date) RETURNS int LANGUAGE sql IMMUTABLE
AS $$ SELECT coalesce(to_char(d, 'YYYYMMDD')::int, -1) $$;
-- "today" for the marts: the as-of date of the latest successful run (definer rights: roles cannot read etl)
CREATE OR REPLACE FUNCTION gold.asof() RETURNS date LANGUAGE sql STABLE SECURITY DEFINER
AS $$ SELECT coalesce((SELECT max(asof_date) FROM etl.run WHERE status <> 'failed'), current_date) $$;
-- the model's random holdout group (Spec 04 §8): fixed at arrival, 10 % of inquiries
CREATE OR REPLACE FUNCTION gold.is_holdout(inquiry_id int) RETURNS int LANGUAGE sql IMMUTABLE
AS $$ SELECT (('x' || left(md5(inquiry_id::text), 7))::bit(28)::int % 10 = 0)::int $$;
CREATE TABLE IF NOT EXISTS work.run_ctx (run_id int, asof date);
