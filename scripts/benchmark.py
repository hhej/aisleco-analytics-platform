"""Performance test (Ch.6 throughput and latency): the initial full load and the daily incremental run at 1× and 10×.

  .venv/bin/python scripts/benchmark.py [--nights 3]

1×: the whole history (2022-07-01 → 2026-10-31), full refresh, then N simulated nights loaded incrementally.
10×: `sim --scale 10` (ten times the couples) over a shorter window (2022-07-01 → 2023-03-31) to keep simulation time
sane, then the same (the simulator cannot start later than 2022-07-01: a later --start writes overlapping contracts).
Per-step seconds come from etl.step_run. Own databases (aisleco_crm_e2e_bench, aisleco_dw_e2e_bench), lake var/bench/,
gateway on :8013. Writes docs/v2/benchmark.md."""
import argparse
import os
import platform
import shutil
import subprocess
import sys
import time
from datetime import date, timedelta
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "var" / "bench"
CRM, DW = "dbname=aisleco_crm_e2e_bench", "dbname=aisleco_dw_e2e_bench"
ENV = {**os.environ, "CRM_DSN": CRM, "DW_DSN": DW, "LAKE_DIR": str(BENCH / "lake"), "SIM_STATE_DIR": str(BENCH / "sim"),
       "GATEWAY_URL": "http://127.0.0.1:8013", "ETL_OFFLINE": "1", "PYTHONUNBUFFERED": "1"}
CASES = [("1×", 1, date(2026, 10, 31)), ("10×", 10, date(2023, 3, 31))]       # (name, scale, last day of the backfill)
GROUPS = {"ingest_crm": "ingest CRM", "ingest_files": "ingest files", "silver": "silver", "load_stg": "load stg",
          "gold_dims": "gold", "fact_inquiry": "gold", "fact_event_booking": "gold", "fact_staff_workload": "gold",
          "fact_sales_activity": "gold", "marts": "marts + checks", "reconcile": "marts + checks", "finish": "marts + checks"}
COLS = ["ingest CRM", "ingest files", "silver", "load stg", "gold", "marts + checks"]
LOG = BENCH / "benchmark.log"


def sh(*args):
    t0 = time.time()
    with open(LOG, "a") as log:
        log.write(f"\n$ {' '.join(args)}\n")
        log.flush()
        if subprocess.run([sys.executable, "-m", *args], env=ENV, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT).returncode:
            sys.exit(f"failed: {' '.join(args)} (see {LOG})")
    return time.time() - t0


def measure():
    with psycopg.connect(DW, row_factory=dict_row) as c:
        run = c.execute("SELECT run_id, mode, extract(epoch FROM finished_at - started_at)::float AS sec FROM etl.run "
                        "ORDER BY run_id DESC LIMIT 1").fetchone()
        steps = c.execute("SELECT step, duration_sec::float AS sec, rows_in, rows_out, metrics FROM etl.step_run "
                          "WHERE run_id = %s AND status = 'success'", (run["run_id"],)).fetchall()
    out = dict.fromkeys(COLS, 0.0)
    for s in steps:
        out[GROUPS[s["step"]]] += s["sec"]
    by = {s["step"]: s for s in steps}
    out.update(mode=run["mode"], total=run["sec"], crm_rows=by["ingest_crm"]["rows_in"], files=by["ingest_files"]["rows_in"],
               silver_rows=by["silver"]["rows_out"],
               fact_changes=sum(by[s]["rows_out"] for s in by if s.startswith("fact_")))
    return out


def crm_size():
    with psycopg.connect(CRM) as c:
        return {t: c.execute(f'SELECT count(*) FROM transaction."{t}"').fetchone()[0]
                for t in ("Inquiry", "ChatMessage", "Event", "EventEmployeeAssignment", "SalesActivity")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nights", type=int, default=3)
    a = ap.parse_args()
    results = []
    for name, scale, end in CASES:
        shutil.rmtree(BENCH, ignore_errors=True)
        BENCH.mkdir(parents=True)
        t_sim = sh("sim", "init", "--reset", "--scale", str(scale)) + sh("sim", "backfill", "--to", str(end))
        size = crm_size()
        print(f"{name}: simulated 2022-07-01 → {end} in {t_sim:.0f}s; CRM {size}", flush=True)
        sh("pipeline", "init", "--drop")
        sh("pipeline", "run", "--asof", str(end + timedelta(1)), "--full-refresh")
        results.append((name, "initial full load", measure(), size))
        print(f"  full load: {results[-1][2]['total']:.1f}s", flush=True)
        for i in range(1, a.nights + 1):
            d = end + timedelta(i)
            day_t = sh("sim", "backfill", "--to", str(d))
            sh("pipeline", "run", "--asof", str(d + timedelta(1)))
            results.append((name, f"daily run {d}", measure(), None))
            print(f"  night {d}: sim {day_t:.1f}s, run {results[-1][2]['total']:.1f}s", flush=True)
    write_report(results, a.nights)


def write_report(results, nights):
    lines = ["# Benchmark: initial load and daily run at 1× and 10×", "",
             f"Generated by `scripts/benchmark.py` on {date.today()}; {platform.machine()} macOS, PostgreSQL 16, DuckDB, "
             "everything on one laptop (Apple M2, 16 GB). Seconds are wall-clock per step from `etl.step_run`.", "",
             f"Method: **1×** simulates the whole history (1 Jul 2022 → {CASES[0][2]}) and loads it with a full refresh; **10×** "
             f"runs the simulator with `--scale 10` (ten times the couples, so about ten times the daily inquiries, messages and "
             f"bookings) over a shorter window (1 Jul 2022 → {CASES[1][2]}) to keep simulation time sane. Each case then "
             f"simulates {nights} more days and loads each with the normal incremental run. Silver is rebuilt from the whole "
             "Bronze history every run, so a daily run's cost grows with history (CRM sizes below) as well as with daily volume.", "",
             "CRM size after the backfill (transaction tables):", ""]
    for name, _, _, size in (r for r in results if r[3]):
        lines.append(f"- {name}: " + ", ".join(f"{t} {n:,}" for t, n in size.items()))
    lines += ["", "| Volume | Run | Total (s) | " + " | ".join(COLS) + " | CRM rows read | Files | CRM rows/s | Gold rows changed |",
              "|---|---|---:|" + "---:|" * len(COLS) + "---:|---:|---:|---:|"]
    for name, label, m, _ in results:
        lines.append(f"| {name} | {label} | {m['total']:.1f} | " + " | ".join(f"{m[c]:.1f}" for c in COLS) +
                     f" | {m['crm_rows']:,} | {m['files']:,} | {m['crm_rows'] / m['total']:,.0f} | {m['fact_changes']:,} |")
    daily10 = [m["total"] for name, label, m, _ in results if name == "10×" and label.startswith("daily")]
    lines += ["", f"Target: daily run under 2 minutes at 10× volume. Measured: max {max(daily10):.1f} s → "
                  f"**{'met' if max(daily10) < 120 else 'NOT met'}**."]
    (ROOT / "docs" / "v2" / "benchmark.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
