"""Model card for the champion lead-conversion model (Spec 04 §10), generated from its ml.model_run record.
Writes docs/v2/model_card_lead_conversion.md."""
import psycopg
from psycopg.rows import dict_row

from ml import data as D
from pipeline.config import ROOT, Config

f3 = lambda v: f"{v:.3f}"
pct = lambda v: f"{v:.0%}"


def run(cfg=None):
    cfg = cfg or Config()
    with psycopg.connect(cfg.dw_dsn, row_factory=dict_row) as c:
        r = c.execute("SELECT * FROM ml.model_run WHERE model = 'lead_conversion' AND status = 'champion' ORDER BY trained_at DESC LIMIT 1").fetchone()
        history = c.execute("SELECT version, status, decision FROM ml.model_run WHERE model = 'lead_conversion' ORDER BY trained_at").fetchall()
    m, t = r["metrics"], r["metrics"]["test"]
    base = m["baselines"]
    lines = [f"# Model card: lead conversion v{r['version']}", "",
             f"Generated by `python -m ml card` from the training record of {r['trained_at']:%d %b %Y}. Registry: MLflow model `lead_conversion`, alias `champion`.", "",
             "## Intended use", "",
             "Ranks each salesperson's open inquiries every morning by expected fee (chance to book × fee), with three plain reasons and a "
             "suggested next action (Spec 04 §7). Users: the sales team (2 salespeople, about 15 follow-ups a day each) and the sales manager.", "",
             "**Not for:** deciding whom *not* to serve. Every couple stays reachable: low-scored leads remain on the list, and 10 % of "
             "inquiries are a random holdout worked newest-first (the A/B comparison, Spec 04 §8).", "",
             "## Data and label", "",
             f"- Unit: an open inquiry on a score date (features as of 00:00, point in time). Label: a booking by the couple within "
             f"{D.LABEL_DAYS} days (window chosen by the pre-registered EDA rule, `docs/v2/ml_eda.md`).",
             f"- Training window {r['train_window']} ({r['train_rows']:,} rows, sampled ages); test window {r['test_window']} "
             f"({r['test_rows']:,} daily rows, out of time, 60-day purge, no inquiry on both sides).",
             f"- Algorithm: {r['algorithm']} (chosen on 5-fold rolling-origin CV: LightGBM {f3(m['cv']['lightgbm'][0])} ± {f3(m['cv']['lightgbm'][1])}, "
             f"logistic regression {f3(m['cv']['logistic regression'][0])} ± {f3(m['cv']['logistic regression'][1])}); isotonic calibration.", "",
             "## Results on the test period", "",
             "| Score | PR-AUC | ROC-AUC | Precision in daily top 5 | Precision in daily top 15 | Bookings caught in top 15 |", "|---|---|---|---|---|---|",
             f"| **Model v{r['version']}** | **{f3(t['pr_auc'])}** (95 % CI {t['pr_auc_ci'][0]:.3f}–{t['pr_auc_ci'][1]:.3f}) | {f3(t['roc_auc'])} | {pct(t['precision_at_5'])} | {pct(t['precision_at_15'])} | {pct(t['bookings_captured'])} |",
             *[f"| {k} | {f3(v['pr_auc'])} | {f3(v['roc_auc'])} | {pct(v['precision_at_5'])} | {pct(v['precision_at_15'])} | {pct(v['bookings_captured'])} |" for k, v in base.items()], "",
             f"- Against today's practice (B0, newest message first): PR-AUC gain **{t['gain_vs_practice']:+.3f}** (95 % CI {t['gain_vs_practice_ci'][0]:+.3f} to {t['gain_vs_practice_ci'][1]:+.3f}).",
             f"- Against the best simple rule ({m['best_baseline']}): {t['gain_vs_best_rule']:+.3f} (95 % CI {t['gain_vs_best_rule_ci'][0]:+.3f} to {t['gain_vs_best_rule_ci'][1]:+.3f}): non-inferior (margin −0.05), likely better.",
             f"- Calibration: expected calibration error {t['ece']:.3f}, Brier {t['brier']:.3f}; base rate {pct(t['base_rate'])}.",
             *([f"- Logistic regression (B3) scores {f3(base['B3 logistic regression']['pr_auc'])} on the test, above the chosen model. The algorithm "
                "was chosen on cross-validation before the test was opened; switching now would choose by the test (leakage), and the gap is "
                "inside the test's confidence interval. Next retraining re-runs the choice on fresh folds."]
               if base.get("B3 logistic regression", {}).get("pr_auc", 0) > t["pr_auc"] else []), "",
             "## What each data source adds (CV ablation)", "", "| + feature group | Features | CV PR-AUC |", "|---|---|---|",
             *[f"| {a['+ group']} | {a['features']} | {a['cv_pr_auc']:.3f} ± {a['cv_sd']:.3f} |" for a in m["ablation"]], "",
             "A data-driven text representation (TF-IDF) was tested on the same folds and dropped: `docs/v2/ml_text_experiment.md`.", "",
             "## Slices (test period, at least 100 rows)", "", "| Slice | Rows | Model PR-AUC | Today's practice PR-AUC |", "|---|---|---|---|",
             *[f"| {k} | {v['rows']:,} | {v['pr_auc']:.3f} | {v['b0_pr_auc']:.3f} |" for k, v in sorted(m["slices"].items())], "",
             "## Gate history (every candidate, promoted or not)", "", "| Version | Status | Decision |", "|---|---|---|",
             *[f"| v{h['version']} | {h['status']} | {h['decision']} |" for h in history], "",
             "## Monitoring and retraining", "",
             "Daily: PSI per feature against the test-period population, missing shares, values outside the training range, score mix. "
             "Weekly: performance on matured labels, overall and on the holdout. Weekly retraining (Sunday) through the same gate; the previous "
             "champion keeps the alias `previous` (`python -m ml rollback`). Results: `ml.monitor`, Data & ML page.", "",
             "## Limits", "",
             "- Simulated data: the drivers are assumptions (Spec 06); the method, not the coefficients, carries over to a real CRM.",
             "- The CRM keeps only the latest quote and budget; edits after the cutoff would leak (none in the simulation; a Quote table fixes it).",
             "- Calibration plateaus (isotonic) give ties; the list breaks them by expected fee.",
             "- Feedback loop: the list changes who is called; the holdout keeps unbiased data for monitoring.", "",
             "## Personal data", "",
             "Features hold no names, phone numbers or text. Message text is read only by the masked restricted Silver table for the "
             "intent tagger and experiments; couple names reach only the Sales role, at display time.", ""]
    out = ROOT / "docs" / "v2" / "model_card_lead_conversion.md"
    out.write_text("\n".join(lines))
    return str(out)
