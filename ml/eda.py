"""EDA report for the lead-conversion model (Spec 04 §10): the evidence behind the label window, class balance, feature
signal, and the 2026 TikTok shift. Writes docs/v2/ml_eda.md with figures in docs/v2/img/."""
from datetime import date

import matplotlib
import pandas as pd

from ml import data as D
from pipeline.config import ROOT

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OUT, IMG = ROOT / "docs" / "v2" / "ml_eda.md", ROOT / "docs" / "v2" / "img"
WINE, GREY = "#7A2E3B", "#9a9893"


def run(asof: date):
    IMG.mkdir(parents=True, exist_ok=True)
    con = D.connect()
    df = D.dataset(con, asof)
    k = df[df.known]
    # 1. label window: for each open day that is followed by a booking, how many days until the booking
    gap = con.execute("""
        SELECT date_diff('day', s.cutoff::DATE, e.booked_at::DATE) AS days
        FROM (SELECT * FROM spine) s JOIN inquiry i USING (inquiry_id)
        JOIN event e ON e.inquiry_id = i.inquiry_id WHERE e.booked_at >= s.cutoff""").df().days
    share = {w: float((gap < w).mean()) for w in (14, 30, 45, 60)}
    fig, ax = plt.subplots(figsize=(6.5, 3.2))
    gap.clip(upper=120).sort_values().reset_index(drop=True).pipe(lambda s: ax.plot(s.values, (s.index + 1) / len(s), color=WINE))
    ax.axvline(30, color=GREY, ls="--", lw=1)
    ax.set(xlabel="days from an open day to the booking", ylabel="share of bookings", title="Time to booking from an open day")
    fig.tight_layout(); fig.savefig(IMG / "eda_time_to_booking.png", dpi=130); plt.close(fig)
    # 2. signal by stage and channel
    by_stage = k.assign(stage=k.quoted.map({1: "quoted"}).fillna(k.consulted.map({1: "consulted"})).fillna("open")).groupby("stage").y.agg(["mean", "size"])
    by_channel = k.groupby("channel").y.agg(["mean", "size"]).sort_values("mean")
    # 3. drift: TikTok share of inquiries by quarter
    tk = con.execute("""SELECT strftime(inquiry_at, '%Y') || '-Q' || quarter(inquiry_at) AS q,
                               avg((c.channel_name = 'TikTok')::INT) AS tiktok, count(*) AS n
                        FROM inquiry i JOIN channel c USING (channel_id) GROUP BY 1 ORDER BY 1""").df()
    fig, ax = plt.subplots(figsize=(6.5, 3))
    ax.bar(tk.q, tk.tiktok, color=[WINE if q.startswith("2026") else GREY for q in tk.q])
    ax.set(title="TikTok share of inquiries by quarter", ylabel="share")
    ax.tick_params(axis="x", labelrotation=60, labelsize=7)
    fig.tight_layout(); fig.savefig(IMG / "eda_tiktok_shift.png", dpi=130); plt.close(fig)
    miss = df[D.FEATURES].isna().mean().sort_values(ascending=False).head(8)
    lines = [f"# Lead-conversion model: exploratory analysis (as of {asof})", "",
             "Generated by `python -m ml eda`. Data: Silver tables, the same feature definition as training and scoring.", "",
             "## Rows and labels", "",
             f"- Training spine: {len(df):,} inquiry-days (each day an inquiry was open, first {D.MAX_AGE} days), {df.inquiry_id.nunique():,} inquiries.",
             f"- Labels known (window over): {len(k):,} rows; positive share {k.y.mean():.2%} (booked within the label window).", "",
             "## Why a 30-day label window", "",
             "![time to booking](img/eda_time_to_booking.png)", "",
             "Share of bookings that happen within N days of an open day that precedes them:", "",
             "| Window | Share of bookings |", "|---|---|", *[f"| {w} days | {v:.0%} |" for w, v in share.items()], "",
             "Rule in Spec 04 §2: the label window is the smallest of 30, 45 and 60 days that holds at least 80 % of bookings. "
             f"Result: **{next((w for w in (30, 45, 60) if share[w] >= 0.8), 60)} days** (the model uses {D.LABEL_DAYS}).", "",
             "## Signal by stage and channel (known rows)", "", "| Stage | Booked within the window | Rows |", "|---|---|---|",
             *[f"| {i} | {r['mean']:.1%} | {int(r['size']):,} |" for i, r in by_stage.iterrows()], "",
             "| Channel | Booked within the window | Rows |", "|---|---|---|",
             *[f"| {i} | {r['mean']:.1%} | {int(r['size']):,} |" for i, r in by_channel.iterrows()], "",
             "## Missing values (top 8 features)", "", "Missing means 'not reached yet' (no quote, no consultation), not an error; "
             "the model gets missing-value indicators, and monitoring watches the missing shares (Spec 04 §9).", "",
             "| Feature | Missing |", "|---|---|", *[f"| {i} | {v:.0%} |" for i, v in miss.items()], "",
             "## The 2026 shift monitoring must catch", "", "![tiktok](img/eda_tiktok_shift.png)", "",
             "TikTok couples are less ready to book; their share rises in 2026, so the base rate falls (label drift) and the channel mix "
             "moves (input drift).", ""]
    OUT.write_text("\n".join(lines))
    return {"report": str(OUT), "share_within_30d": share[30]}
