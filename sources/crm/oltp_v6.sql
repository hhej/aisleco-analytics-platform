-- Changes from v5 (docs/v2/01_sources_and_ingestion.md §2.1):
--   + master.EmployeeContract (role and hours history; SCD2 source)
--   + transaction.SalesActivity (every follow-up; written by the web app)
--   + Inquiry.AssignedSalesEmployeeID, Event.CancelledDate
--   - AuspiciousDate (now an external source)
--   CreatedAt + UpdatedAt on every table (UpdatedAt kept by trigger, oltp_v6_support.sql)
-- dbdiagram.io: Import -> PostgreSQL, this file only.
